#!/usr/bin/env node
// Generates engine/src/constants.gen.hpp from engine/constants.yaml (K4 single
// constants table, 2026-07-19). Deterministic: same input, byte-identical
// output. The K4 relocation NEVER changes a value — the golden byte-identical
// diff is the guard; this generator only moves where the number lives.
// Pass --check to verify the committed output is in sync (exit 1 on drift).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../..');
const yamlPath = join(root, 'engine/constants.yaml');

// --- minimal YAML subset parser (this file's fixed shape only) ----------------
// Shape: top-level `version: N` + `constants:` list of flat maps. Values are
// scalars or double-quoted strings. No nesting beyond that — by design, so the
// table stays trivially parseable with zero dependencies.
export function parseConstantsYaml(text) {
  const rows = [];
  let version = null;
  let cur = null;
  for (const raw of text.split('\n')) {
    const line = raw.replace(/\t/g, '  ');
    if (/^\s*(#|$)/.test(line)) continue;
    let m;
    if ((m = line.match(/^version:\s*(\d+)\s*$/))) { version = Number(m[1]); continue; }
    if (/^constants:\s*$/.test(line)) continue;
    if ((m = line.match(/^  - name:\s*(\S+)\s*$/))) { cur = { name: m[1] }; rows.push(cur); continue; }
    if ((m = line.match(/^    (\w+):\s*(.*\S)\s*$/))) {
      if (!cur) throw new Error(`field before first row: ${line}`);
      let v = m[2];
      if (v.startsWith('"') && v.endsWith('"')) v = v.slice(1, -1);
      cur[m[1]] = v;
      continue;
    }
    throw new Error(`unparseable line in constants.yaml: ${JSON.stringify(raw)}`);
  }
  return { version, rows };
}

const { version, rows } = parseConstantsYaml(readFileSync(yamlPath, 'utf8'));

// --- validation ---------------------------------------------------------------
const STATUSES = new Set(['verified', 'assumed', 'refuted']);
const UNITS = new Set(['mm', 'ratio', 'deg']);
const seen = new Set();
if (version !== 1) throw new Error(`constants.yaml version ${version} unsupported`);
for (const r of rows) {
  for (const f of ['name', 'value', 'unit', 'source', 'status', 'experiment']) {
    if (!(f in r)) throw new Error(`row ${r.name || '?'} missing field ${f}`);
  }
  if (seen.has(r.name)) throw new Error(`duplicate constant ${r.name}`);
  seen.add(r.name);
  if (!STATUSES.has(r.status)) throw new Error(`row ${r.name}: bad status ${r.status}`);
  if (!UNITS.has(r.unit)) throw new Error(`row ${r.name}: bad unit ${r.unit}`);
  if (!/^-?\d+(\.\d+)?$/.test(r.value)) throw new Error(`row ${r.name}: bad value ${r.value}`);
}

// --- C++ ----------------------------------------------------------------------
const sym = (n) => 'k' + n[0].toUpperCase() + n.slice(1);
let hpp = `#pragma once
// GENERATED by engine/tools/gen-constants.mjs from engine/constants.yaml — DO NOT EDIT.
// The K4 constants table relocates embedded design assumptions; it never
// changes them. The golden reference is the guard: a value drift here fails
// the byte-identical diff. Status per row (verified/assumed/refuted) lives in
// constants.yaml with its source + experiment; refuted values stay unchanged
// in this chain (a value change is a behaviour change — v1.1 candidates).

namespace stitchu {
namespace constants {

`;
for (const r of rows) {
  hpp += `// ${r.name} [${r.unit}] — ${r.status}\n`;
  hpp += `inline constexpr double ${sym(r.name)} = ${r.value};\n`;
}
hpp += `\n} // namespace constants\n} // namespace stitchu\n`;

// --- write / check ------------------------------------------------------------
const outPath = join(root, 'engine/src/constants.gen.hpp');
if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(outPath, 'utf8'); } catch { /* missing counts as drift */ }
  if (cur !== hpp) {
    console.error('DRIFT: engine/src/constants.gen.hpp out of sync with engine/constants.yaml (run gen-constants.mjs)');
    process.exit(1);
  }
  console.log(`constants.gen.hpp in sync (${rows.length} constants)`);
} else {
  writeFileSync(outPath, hpp);
  console.log(`wrote engine/src/constants.gen.hpp (${rows.length} constants)`);
}
