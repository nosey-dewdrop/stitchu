#!/usr/bin/env node
// gen-flat-tables.mjs — the five contract tables the FLAT PEN reads, emitted as
// one browser-loadable ES module: web/lib/flat-tables.gen.js
//
// WHY THIS FILE EXISTS (F-İNDİR, 2. tur, 2026-08-26). The referee measured the
// phase's own claim and it was too wide: web/js/download.js exports ten
// functions and all ten write a PATTERN. `grep -i flat` over it found a comment
// and nothing else. So the target sentence — photo + prompt -> pattern + FLAT —
// was half true: the pattern came home, the flat stayed on the screen. Worse,
// measured: the flat was not even on create.html's screen. The only shipped
// surface carrying a flat is web/atolye.html, which embeds the READ-ONLY
// reference pen; the production pen (engine/tools/render-garment-flat.mjs) has
// never printed a pixel a shopper could see (GECE/V4-D's sharpest finding,
// re-verified here: `grep -rn data-engine-gap web/` = 0 before this change).
//
// The production pen is pure ESM and its only node dependency was five
// readFileSync calls at module load. That is the whole reason it could not run
// in a browser. This generator removes that dependency the way this repo
// already removes it elsewhere (gen-contract.mjs -> web/js/contract.gen.js):
// the tables are emitted as a module, and a --check gate fails when the emitted
// module drifts from the contract files it was made from.
//
// WHAT IS NOT DUPLICATED. The pen itself is MOVED, not copied — web/lib/
// flat-core.js is the body and engine/tools/render-garment-flat.mjs is a
// one-line re-export so that all fifteen node callers keep their import path.
// There is one pen. Only the five JSON tables are mirrored, and a mirror with a
// --check gate on it is a build artefact, not a second truth.
//
//   node engine/tools/gen-flat-tables.mjs           -> writes
//   node engine/tools/gen-flat-tables.mjs --check   -> compares, exit 1 on drift
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../..');
const OUT = 'web/lib/flat-tables.gen.js';

// name in the pen -> source file. Order is fixed so the output is deterministic.
const SOURCES = [
  ['LAW', 'contract/flat-convention-v1.json'],
  ['SICIL', 'contract/garment-spec-v2.json'],
  ['VOCAB', 'engine/vocab.json'],
  ['GRAMMAR', 'contract/spec-grammar.json'],
  ['V1V2', 'contract/spec-v1-v2-map.json'],
];

let out = '// GENERATED by engine/tools/gen-flat-tables.mjs — DO NOT EDIT.\n';
out += '// The five contract tables web/lib/flat-core.js reads, so the flat pen runs\n';
out += '// in a browser (no node:fs). Gate: ctest -R flat_tables_check.\n';
out += '// Sources:\n';
for (const [, src] of SOURCES) out += `//   ${src}\n`;
out += '\n';
for (const [name, src] of SOURCES) {
  const json = JSON.parse(readFileSync(join(root, src), 'utf8'));
  out += `export const ${name} = ${JSON.stringify(json, null, 2)};\n\n`;
}

const path = join(root, OUT);
if (process.argv.includes('--check')) {
  let have = '';
  try { have = readFileSync(path, 'utf8'); } catch { have = ''; }
  if (have !== out) {
    console.error(`FAIL ${OUT} is stale — regenerate: node engine/tools/gen-flat-tables.mjs`);
    process.exit(1);
  }
  console.log(`OK ${OUT} matches ${SOURCES.length} contract tables`);
  process.exit(0);
}
writeFileSync(path, out);
console.log(`wrote ${OUT} (${out.length} bytes, ${SOURCES.length} tables)`);
