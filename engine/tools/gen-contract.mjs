#!/usr/bin/env node
// Generates the contract consumer tables from contract/tables.json + the
// vision-reading schema slice of contract/garment-spec.schema.json (K1 single
// contract, 2026-07-19). Deterministic: same input, byte-identical output.
// Outputs:
//   engine/src/contract.gen.hpp  (C++ shared values: skirt lengths, gather
//                                 ratios, EU size chart — the SAME numbers,
//                                 relocated; golden must stay byte-identical)
//   web/js/contract.gen.js       (JS tables + the embedded visionReading
//                                 schema for the runtime validator)
//   backend/contract.gen.js      (same module for the Cloudflare Worker)
// Pass --check to verify the committed outputs are in sync (exit 1 on drift).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../..');
const tables = JSON.parse(readFileSync(join(root, 'contract/tables.json'), 'utf8'));
const schema = JSON.parse(readFileSync(join(root, 'contract/garment-spec.schema.json'), 'utf8'));
const composition = JSON.parse(readFileSync(join(root, 'contract/composition.json'), 'utf8'));
// F2-vision (2026-09-01): the photo-reading→engine carriage contract (ratio
// wires + out-of-vocab mapping table). Data lives in the contract dir; the
// browser bridge (vision-bridge.js) consumes it through contract.gen.js so the
// table is DATA, never code (KOSU F2 rule: esleme tablosu contract'a veri olarak).
const visionTasima = JSON.parse(readFileSync(join(root, 'contract/vision-tasima-v1.json'), 'utf8'));
// F5-parca (2026-09-02): geçiş kuralı (fermuar ne zaman gerekir) + pens
// eskalasyonu eşikleri. Değerler contract/parca-gecis-v1.json'da KAYNAKLARIYLA
// durur; C++ bu üretimden okur, koda gömülü kopya yok (görev kuralı: eşikler
// contract'tan okunur).
const parcaGecis = JSON.parse(readFileSync(join(root, 'contract/parca-gecis-v1.json'), 'utf8'));
// F7-edit (2026-09-02): the edit-locality contract (zone -> untouchable panel
// patterns, field -> zones) reaches the BROWSER through this generation, so the
// create screen can run the same locality judgement the gate runs — data from
// the contract dir, never a copy typed into web/js.
const editLocality = JSON.parse(readFileSync(join(root, 'contract/edit-locality-v1.json'), 'utf8'));
// M3-primitif (2026-09-03): the Katman 3 -> Katman 1 resolution table
// (contract/vocab-resolution-v1.json). Only the SLICE the out-of-vocab mapping
// can reach is embedded — the keys `oovEsleme` names with `durum: 'eslendi'`.
// Reason it is a slice and not the whole 68 KB table: the browser needs exactly
// the bundles an out-of-vocab word can resolve to, and shipping 132 entries to
// every visitor to serve 25 would be paying for the other 107 on every page
// load. The gate (engine/tests/primitif_ifade_check.mjs) reads the FULL table
// off disk, so nothing is hidden by the slice.
const vocabResolution = JSON.parse(readFileSync(join(root, 'contract/vocab-resolution-v1.json'), 'utf8'));
const primitifCozum = {};
for (const rule of visionTasima.oovEsleme.kurallar) {
  if (rule.durum !== 'eslendi' || !rule.eksen || rule.deger === undefined) continue;
  const key = `${rule.eksen}.${rule.deger}`;
  const entry = vocabResolution.resolutions[key];
  if (!entry) throw new Error(`oovEsleme rule '${rule.ad}' names ${key}, absent from vocab-resolution-v1.json`);
  primitifCozum[key] = { status: entry.status, bundle: entry.bundle || [], note: entry.note || '' };
}

const HEADER = 'GENERATED by engine/tools/gen-contract.mjs from contract/tables.json — DO NOT EDIT.';

// ---- C++ ---------------------------------------------------------------------
// Number formatting: emit integers bare, non-integers as written in JSON.
const num = (v) => (Number.isInteger(v) ? String(v) : String(v));
let hpp = `#pragma once\n// ${HEADER}\n// The K1 contract relocates shared values; it never changes them. The golden\n// reference is the guard: a value drift here fails the byte-identical diff.\n\nnamespace stitchu {\nnamespace contract {\n\n`;
hpp += `// draft.skirtLengthMM — real hem drop in millimetres (measurements.hpp reads these)\n`;
for (const [k, v] of Object.entries(tables.draft.skirtLengthMM)) {
  hpp += `inline constexpr double kSkirtLength_${k} = ${num(v)};\n`;
}
hpp += `\n// draft.gatherRatios — flat cut width / finished gathered width (gather.cpp reads these)\n`;
for (const [k, v] of Object.entries(tables.draft.gatherRatios)) {
  if (k.startsWith('_')) continue;
  hpp += `inline constexpr double kGatherRatio_${k} = ${num(v)};\n`;
}
hpp += `\n// draft.euSizeChart — standard bodies (sizechart.hpp expands this X-macro).\n// Columns: ${tables.draft.euSizeChart._fields.join(', ')}\n`;
hpp += `#define STITCHU_CONTRACT_EU_SIZE_CHART(X) \\\n`;
const chartRows = tables.draft.euSizes.map((label) => {
  const row = tables.draft.euSizeChart[label];
  return `    X("${label}", ${row.map(num).join(', ')})`;
});
hpp += chartRows.join(' \\\n') + '\n';
hpp += `\n// contract/parca-gecis-v1.json — geçiş kuralı + pens eskalasyonu (F5-parca).\n`;
hpp += `// Baş çevresi referansı: theknitwit.org "minimum neck opening = head circumference / stretch ratio".\n`;
hpp += `inline constexpr double kHeadCircumferenceMM = ${num(parcaGecis.gecis_kurali.headCircumferenceMM)};\n`;
hpp += `// Tek pens ağzı tavanı (anicka.design, KAYNAK ZAYIF — blog): üstü iki pense bölünür.\n`;
hpp += `inline constexpr double kMaxSingleDartMouthMM = ${num(parcaGecis.pens_eskalasyonu.maxSingleDartMouthMM)};\n`;
hpp += `// Supresyon dağılım bandı (anicka.design, KAYNAK ZAYIF) — KAYIT, tele bağlı değil\n`;
hpp += `// (contract dosyasındaki _uygulama notu: Aldrich pens derinliği kararıyla çelişir).\n`;
hpp += `inline constexpr double kSuppressionSideShare = ${num(parcaGecis.pens_eskalasyonu.supresyon_dagilimi.yanShare)};\n`;
hpp += `inline constexpr double kSuppressionDartShare = ${num(parcaGecis.pens_eskalasyonu.supresyon_dagilimi.pensShare)};\n`;
hpp += `// FBA -> prenses bandı (curvysewingcollective, KAYNAK ZAYIF) — KAYIT.\n`;
hpp += `inline constexpr double kFbaPrincessMinMM = ${num(parcaGecis.pens_eskalasyonu.fbaPrenses.minMM)};\n`;
hpp += `inline constexpr double kFbaPrincessMaxMM = ${num(parcaGecis.pens_eskalasyonu.fbaPrenses.maxMM)};\n`;
hpp += `\n} // namespace contract\n} // namespace stitchu\n`;

// ---- JS (web + worker share the same content) --------------------------------
const pub = {
  version: tables.version,
  draft: {
    skirtLengthMM: tables.draft.skirtLengthMM,
    gatherRatios: Object.fromEntries(Object.entries(tables.draft.gatherRatios).filter(([k]) => !k.startsWith('_'))),
    euSizes: tables.draft.euSizes,
    euSizeChart: Object.fromEntries(tables.draft.euSizes.map((label) => [label, tables.draft.euSizeChart[label]])),
    euSizeChartFields: tables.draft.euSizeChart._fields,
  },
  flat: { unitPX: tables.flat.unitPX, len: tables.flat.len, size: tables.flat.size },
  mappings: {
    sleeveHeadToSleeveCap: Object.fromEntries(Object.entries(tables.mappings.sleeveHeadToSleeveCap).filter(([k]) => !k.startsWith('_'))),
    nullEquivalence: Object.fromEntries(Object.entries(tables.mappings.nullEquivalence).filter(([k]) => !k.startsWith('_'))),
    backDetailSplit: Object.fromEntries(Object.entries(tables.mappings.backDetailSplit).filter(([k]) => !k.startsWith('_'))),
    seenFlags: tables.mappings.seenFlags,
  },
};
let js = `// ${HEADER}\n// Single source for every shared cross-layer value + the vision-reading\n// schema (embedded from contract/garment-spec.schema.json $defs.visionReading\n// so the browser validates without fetching the contract dir).\n\nexport const CONTRACT = ${JSON.stringify(pub, null, 2)};\n\nexport const VISION_SCHEMA = ${JSON.stringify(schema.$defs.visionReading, null, 2)};\n\n// F2-vision: photo-reading carriage contract (embedded from\n// contract/vision-tasima-v1.json — ratio wires + out-of-vocab mapping).\nexport const VISION_TASIMA = ${JSON.stringify(visionTasima, null, 2)};\n\n// F7-edit: edit-locality contract (embedded from contract/edit-locality-v1.json)\n// — zones + untouchable panel patterns + field->zone map, so the create screen\n// runs the SAME locality judgement the gate (edit_locality_check.mjs) runs.\nexport const EDIT_LOCALITY = ${JSON.stringify({ zones: editLocality.zones, fieldZones: editLocality.fieldZones }, null, 2)};\n\n// M3-primitif: KATMAN 3 -> KATMAN 1 cozumu. Bir sozluk-disi kelime bir eksene\n// eslendiginde cevap bir EKSEN ADI degil, bir PRIMITIF DEMETI olsun diye burada.\n// Kaynak contract/vocab-resolution-v1.json; kopya degil, uretim.\nexport const PRIMITIF_COZUM = ${JSON.stringify(primitifCozum, null, 2)};\n`;

// ---- C++ composition matrix (K2) ---------------------------------------------
// compose_check (ctest) re-derives every class by drafting and compares against
// these declared rules. The matrix declares behavior, it never changes it.
const esc = (s) => String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
let comp = `#pragma once\n// GENERATED by engine/tools/gen-contract.mjs from contract/composition.json — DO NOT EDIT.\n// K2 composition contract (2026-07-19): the declared component x host and\n// component x component conflict matrix. engine/tests/compose_check.cpp is the\n// ratchet: it drafts every combination and fails on any declared-vs-observed drift.\n\nnamespace stitchu {\nnamespace contract {\n\nstruct ComposeRule { const char* host; const char* feature; const char* cls; };\nstruct ComposePair { const char* a; const char* b; const char* cls; };\n\ninline constexpr ComposeRule kComposeHostRules[] = {\n`;
for (const r of composition.matrix.hostRules) {
  comp += `    {"${esc(r.host)}", "${esc(r.feature)}", "${esc(r.class)}"},\n`;
}
comp += `};\n\ninline constexpr ComposePair kComposePairRules[] = {\n`;
for (const r of composition.matrix.pairRules) {
  comp += `    {"${esc(r.a)}", "${esc(r.b)}", "${esc(r.class)}"},\n`;
}
comp += `};\n\n} // namespace contract\n} // namespace stitchu\n`;


// ---- body-v1 (F1, 2026-09-05) ------------------------------------------------
// contract/body-v1.json -> engine/src/body.gen.hpp. Iki beden (gercek36,
// croquis36), landmark/halka/uzunluk/genislik/aci tablolari, 34-44 grade
// sutunlari ve croquis oranlari. Cekirdek C++ (iOS/sunucu/wasm) JSON okumaz;
// sayilar contract'tan BURAYA uretilir, koda gomulmez (body.cpp yalniz okur).
const bodyV1 = JSON.parse(readFileSync(join(root, 'contract/body-v1.json'), 'utf8'));
const bnum = (v) => (v === null || v === undefined) ? 'kNoValue' : String(v);
let bh = `#pragma once\n// GENERATED by engine/tools/gen-contract.mjs from contract/body-v1.json — DO NOT EDIT.\n// kNoValue (NaN) = contract'ta null (kaynak bulunamadi); body.cpp bunu 'yok' okur.\n#include <limits>\n\nnamespace stitchu {\nnamespace contract {\n\nconstexpr double kNoValue = std::numeric_limits<double>::quiet_NaN();\n\nstruct BodyLandmarkRow { const char* name; double x, y; };\nstruct BodyGirthRow { const char* name; double girthMM, backFrac; };\nstruct BodyScalarRow { const char* name; double v; };\n\n`;
for (const bodyId of ['gercek36', 'croquis36']) {
  const B = bodyV1.bedenler[bodyId];
  bh += `inline constexpr BodyLandmarkRow kBodyLandmarks_${bodyId}[] = {\n`;
  for (const [k, v] of Object.entries(B.landmarklar)) bh += `    {"${k}", ${bnum(v.x)}, ${bnum(v.y)}},\n`;
  bh += `};\ninline constexpr BodyGirthRow kBodyGirths_${bodyId}[] = {\n`;
  for (const [k, v] of Object.entries(B.halkalar)) if (!k.startsWith('_')) bh += `    {"${k}", ${bnum(v.cevreMM)}, ${bnum(v.arkaPay)}},\n`;
  bh += `};\ninline constexpr BodyScalarRow kBodyScalars_${bodyId}[] = {\n`;
  for (const grp of ['uzunluklar', 'genislikler']) for (const [k, v] of Object.entries(B[grp])) if (!k.startsWith('_')) bh += `    {"${k}", ${bnum(v.mm)}},\n`;
  for (const [k, v] of Object.entries(B.acilar)) bh += `    {"${k}", ${bnum(v.deg)}},\n`;
  bh += `};\n\n`;
}
bh += `// farkTablosu: croquis36 - gercek36 (dx, dy), mm\ninline constexpr BodyLandmarkRow kBodyFark[] = {\n`;
for (const [k, v] of Object.entries(bodyV1.bedenler.farkTablosu.landmark)) bh += `    {"${k}", ${bnum(v.dx)}, ${bnum(v.dy)}},\n`;
bh += `};\n\n`;
const grade = bodyV1.gradeTablosu.degerler;
const gsz = grade._sutunlar;
bh += `inline constexpr int kBodyGradeCount = ${gsz.length};\ninline constexpr const char* kBodyGradeSizes[kBodyGradeCount] = {${gsz.map((s) => `"${s}"`).join(', ')}};\nstruct BodyGradeCol { const char* name; double v[kBodyGradeCount]; };\ninline constexpr BodyGradeCol kBodyGradeCols[] = {\n`;
for (const [k, v] of Object.entries(grade)) {
  if (k.startsWith('_') || k === 'arkaPay') continue;
  const arr = v.mm ?? v.deg;
  if (!Array.isArray(arr) || arr.length !== gsz.length) throw new Error(`body-v1 gradeTablosu.degerler.${k}: ${gsz.length} deger bekleniyor`);
  bh += `    {"${k}", {${arr.map(bnum).join(', ')}}},\n`;
}
for (const ring of ['bust', 'waist', 'hip']) bh += `    {"arkaPay.${ring}", {${grade.arkaPay['girth.' + ring].map(bnum).join(', ')}}},\n`;
bh += `};\ninline constexpr BodyScalarRow kBodyGradeConst[] = {\n`;
for (const [k, v] of Object.entries(grade._sabitler)) if (typeof v === 'number') bh += `    {"${k}", ${bnum(v)}},\n`;
bh += `};\n\n`;
const co = bodyV1.bedenler.croquis36.croquisOranlar;
bh += `inline constexpr BodyScalarRow kCroquisOran[] = {\n`;
for (const [k, v] of Object.entries(co)) if (typeof v === 'number') bh += `    {"${k}", ${bnum(v)}},\n`;
bh += `};\n\ninline constexpr BodyScalarRow kBodyKesitOran[] = {\n`;
// F1 tur 5: croquis tek genislik yasasi (bolluk yalniz belde) + omuz hukmu SOZLESMEDE (karar ajani 2), body_check okur/basar
{
  const cb = bodyV1.bedenler.croquis36.croquisBolluk;
  if (!cb || typeof cb['girth.waist'] !== 'number') throw new Error('body-v1 croquis36.croquisBolluk.girth.waist yok');
  const oh = bodyV1.bedenler.croquis36._omuzHukmu;
  if (typeof oh !== 'string' || oh.length < 40) throw new Error('body-v1 croquis36._omuzHukmu yok (karar ajani 2)');
  bh = bh.replace(/\n\ninline constexpr BodyScalarRow kBodyKesitOran\[\] = \{\n$/, '');
  bh += `\ninline constexpr BodyScalarRow kCroquisBolluk[] = {\n`;
  for (const [k, v] of Object.entries(cb)) if (typeof v === 'number') bh += `    {"${k}", ${bnum(v)}},\n`;
  bh += `};\ninline constexpr const char* kCroquisOmuzHukmu = ${JSON.stringify(oh)};\n\ninline constexpr BodyScalarRow kBodyKesitOran[] = {\n`;
}
for (const [k, v] of Object.entries(bodyV1.halkaKesitOran)) if (typeof v === 'number') bh += `    {"${k}", ${bnum(v)}},\n`;
bh += `};\n\n`;
// landmarkSirasi (F1 duzeltme 2, karar ajani 1): y sirasi contract'tan okunur, testte
// varsayim olarak yazilmaz. Tier: ayni tier icinde esit y izinli, tier'lar arasi kesin artan.
// Iki bedenin sirasi FARKLI olabilir (HEDEF 4): croquis36'da koltukalti gogus hattinin altinda.
bh += `struct BodyOrderRow { const char* name; int tier; };\n`;
for (const bodyId of ['gercek36', 'croquis36']) {
  const tiers = bodyV1.bedenler[bodyId].landmarkSirasi;
  if (!Array.isArray(tiers) || !tiers.length) throw new Error(`body-v1 bedenler.${bodyId}.landmarkSirasi yok`);
  bh += `inline constexpr BodyOrderRow kBodyOrder_${bodyId}[] = {\n`;
  tiers.forEach((tier, i) => { for (const n of tier) bh += `    {"${n}", ${i}},\n`; });
  bh += `};\n`;
}
// cizimYardimcisi: yalniz beden-iki.svg (body_check fig()) icin; kalip/flat okumaz. DOGRULANMADI beyanli.
bh += `\ninline constexpr BodyScalarRow kBodyCizimYardimcisi[] = {\n`;
for (const [k, v] of Object.entries(bodyV1.cizimYardimcisi)) if (typeof v === 'number') bh += `    {"${k}", ${bnum(v)}},\n`;
bh += `};\n`;
// croquis bandlari: figure-bands.json (waist/bust, bust/hip yarim genislik) + flat-convention sevkPoz
// (omuz/gogus orani, omuz egimi). body_check (f) bunlari BURADAN okur (F1 hakem: 0.72/0.84... testte gomuluydu).
const figureBands = JSON.parse(readFileSync(join(root, 'contract/figure-bands.json'), 'utf8'));
const flatLaw = JSON.parse(readFileSync(join(root, 'contract/flat-convention-v1.json'), 'utf8'));
const bandRows = [
  ['waistHalfOverBustHalf', figureBands.ratios.waist_bust.band, 'figure-bands ratios.waist_bust.band'],
  ['bustHalfOverHipHalf', figureBands.ratios.bust_hip.band, 'figure-bands ratios.bust_hip.band'],
  ['shoulderTipXOverBustHalf', [flatLaw.sevkPoz.omuzGogusOran.min, flatLaw.sevkPoz.omuzGogusOran.max], 'flat-convention sevkPoz.omuzGogusOran'],
  ['shoulderSlopeDeg', [flatLaw.sevkPoz.omuzEgimiDeg.min, flatLaw.sevkPoz.omuzEgimiDeg.max], 'flat-convention sevkPoz.omuzEgimiDeg'],
];
bh += `\nstruct BodyBandRow { const char* name; double lo, hi; const char* kaynak; };\ninline constexpr BodyBandRow kCroquisBand[] = {\n`;
for (const [n, [lo, hi], src] of bandRows) {
  if (!(Number.isFinite(lo) && Number.isFinite(hi) && lo < hi)) throw new Error(`band ${n} okunamadi (${src})`);
  bh += `    {"${n}", ${bnum(lo)}, ${bnum(hi)}, "${src}"},\n`;
}
bh += `};\n`;
// Tek kaynak bekcisi (karar ajani 1/F1 hakem kusuru 4): croquis kol acisi sevkPoz tabanidir, kopya degil.
if (co.kolAcisiDeg !== flatLaw.sevkPoz.kolAcisiDeg.taban) throw new Error(`body-v1 croquisOranlar.kolAcisiDeg ${co.kolAcisiDeg} != flat-convention sevkPoz.kolAcisiDeg.taban ${flatLaw.sevkPoz.kolAcisiDeg.taban}`);
bh += `\ninline constexpr double kBodyKapiToleransMM = ${bnum(bodyV1.ayniInsan.kapiToleransMM.deger)};\ninline constexpr double kAyniInsanToleransMM = ${bnum(bodyV1.ayniInsan.toleransMM)};\n\n} // namespace contract\n} // namespace stitchu\n`;

// ---- pattern-sheet-v1 bekcisi (F1 duzeltme 2, karar ajani 5) ------------------
// Centik tip kumesi ASTM D6673 adlariyla contract'ta; varsayilanTip kume icinde ve
// katman o tipin ASTM katmani olmak zorunda. F2b kalip SVG'si bu alanlari okur.
const patternSheet = JSON.parse(readFileSync(join(root, 'contract/pattern-sheet-v1.json'), 'utf8'));
{
  const c = patternSheet.centik;
  if (!c || typeof c.tipler !== 'object') throw new Error('pattern-sheet-v1 centik.tipler yok');
  if (!(c.varsayilanTip in c.tipler)) throw new Error(`pattern-sheet-v1 centik.varsayilanTip '${c.varsayilanTip}' tipler kumesinde degil (${Object.keys(c.tipler).join(', ')})`);
  if (c.katman !== c.tipler[c.varsayilanTip]) throw new Error(`pattern-sheet-v1 centik.katman ${c.katman} != tipler.${c.varsayilanTip} ${c.tipler[c.varsayilanTip]} (ASTM D6673 katmani)`);
}

// ---- write / check -----------------------------------------------------------
const outputs = [
  ['engine/src/contract.gen.hpp', hpp],
  ['engine/src/composition.gen.hpp', comp],
  ['engine/src/body.gen.hpp', bh],
  ['web/js/contract.gen.js', js],
  ['backend/contract.gen.js', js],
];
const check = process.argv.includes('--check');
let drift = 0;
for (const [rel, content] of outputs) {
  const path = join(root, rel);
  if (check) {
    let cur = '';
    try { cur = readFileSync(path, 'utf8'); } catch { /* missing counts as drift */ }
    if (cur !== content) { console.error(`DRIFT: ${rel} out of sync with contract/tables.json (run gen-contract.mjs)`); drift = 1; }
  } else {
    writeFileSync(path, content);
  }
}
if (check) {
  if (drift) process.exit(1);
  console.log('contract.gen outputs in sync');
} else {
  console.log('wrote ' + outputs.map(([r]) => r).join(', '));
}
