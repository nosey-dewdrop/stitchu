#!/usr/bin/env node
// Generates the contract consumer tables from contract/tables.json + the
// vision-reading schema slice of contract/garment-spec.schema.json (K1 single
// contract, 2026-07-19). Deterministic: same input, byte-identical output.
// Outputs:
//   engine/src/contract.gen.hpp  (C++ shared values: skirt lengths, gather
//                                 ratios, EU size chart — the SAME numbers,
//                                 relocated; golden must stay byte-identical)
//   web/js/contract.gen.js       (JS tables + the embedded visionReading
//                                 schema for the runtime validator)
//   backend/contract.gen.js      (same module for the Cloudflare Worker)
// Pass --check to verify the committed outputs are in sync (exit 1 on drift).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../..');
const tables = JSON.parse(readFileSync(join(root, 'contract/tables.json'), 'utf8'));
const schema = JSON.parse(readFileSync(join(root, 'contract/garment-spec.schema.json'), 'utf8'));
const composition = JSON.parse(readFileSync(join(root, 'contract/composition.json'), 'utf8'));
// F2-vision (2026-09-01): the photo-reading→engine carriage contract (ratio
// wires + out-of-vocab mapping table). Data lives in the contract dir; the
// browser bridge (vision-bridge.js) consumes it through contract.gen.js so the
// table is DATA, never code (KOSU F2 rule: esleme tablosu contract'a veri olarak).
const visionTasima = JSON.parse(readFileSync(join(root, 'contract/vision-tasima-v1.json'), 'utf8'));
// F5-parca (2026-09-02): geçiş kuralı (fermuar ne zaman gerekir) + pens
// eskalasyonu eşikleri. Değerler contract/parca-gecis-v1.json'da KAYNAKLARIYLA
// durur; C++ bu üretimden okur, koda gömülü kopya yok (görev kuralı: eşikler
// contract'tan okunur).
const parcaGecis = JSON.parse(readFileSync(join(root, 'contract/parca-gecis-v1.json'), 'utf8'));
// F7-edit (2026-09-02): the edit-locality contract (zone -> untouchable panel
// patterns, field -> zones) reaches the BROWSER through this generation, so the
// create screen can run the same locality judgement the gate runs — data from
// the contract dir, never a copy typed into web/js.
const editLocality = JSON.parse(readFileSync(join(root, 'contract/edit-locality-v1.json'), 'utf8'));

const HEADER = 'GENERATED by engine/tools/gen-contract.mjs from contract/tables.json — DO NOT EDIT.';

// ---- C++ ---------------------------------------------------------------------
// Number formatting: emit integers bare, non-integers as written in JSON.
const num = (v) => (Number.isInteger(v) ? String(v) : String(v));
let hpp = `#pragma once\n// ${HEADER}\n// The K1 contract relocates shared values; it never changes them. The golden\n// reference is the guard: a value drift here fails the byte-identical diff.\n\nnamespace stitchu {\nnamespace contract {\n\n`;
hpp += `// draft.skirtLengthMM — real hem drop in millimetres (measurements.hpp reads these)\n`;
for (const [k, v] of Object.entries(tables.draft.skirtLengthMM)) {
  hpp += `inline constexpr double kSkirtLength_${k} = ${num(v)};\n`;
}
hpp += `\n// draft.gatherRatios — flat cut width / finished gathered width (gather.cpp reads these)\n`;
for (const [k, v] of Object.entries(tables.draft.gatherRatios)) {
  if (k.startsWith('_')) continue;
  hpp += `inline constexpr double kGatherRatio_${k} = ${num(v)};\n`;
}
hpp += `\n// draft.euSizeChart — standard bodies (sizechart.hpp expands this X-macro).\n// Columns: ${tables.draft.euSizeChart._fields.join(', ')}\n`;
hpp += `#define STITCHU_CONTRACT_EU_SIZE_CHART(X) \\\n`;
const chartRows = tables.draft.euSizes.map((label) => {
  const row = tables.draft.euSizeChart[label];
  return `    X("${label}", ${row.map(num).join(', ')})`;
});
hpp += chartRows.join(' \\\n') + '\n';
hpp += `\n// contract/parca-gecis-v1.json — geçiş kuralı + pens eskalasyonu (F5-parca).\n`;
hpp += `// Baş çevresi referansı: theknitwit.org "minimum neck opening = head circumference / stretch ratio".\n`;
hpp += `inline constexpr double kHeadCircumferenceMM = ${num(parcaGecis.gecis_kurali.headCircumferenceMM)};\n`;
hpp += `// Tek pens ağzı tavanı (anicka.design, KAYNAK ZAYIF — blog): üstü iki pense bölünür.\n`;
hpp += `inline constexpr double kMaxSingleDartMouthMM = ${num(parcaGecis.pens_eskalasyonu.maxSingleDartMouthMM)};\n`;
hpp += `// Supresyon dağılım bandı (anicka.design, KAYNAK ZAYIF) — KAYIT, tele bağlı değil\n`;
hpp += `// (contract dosyasındaki _uygulama notu: Aldrich pens derinliği kararıyla çelişir).\n`;
hpp += `inline constexpr double kSuppressionSideShare = ${num(parcaGecis.pens_eskalasyonu.supresyon_dagilimi.yanShare)};\n`;
hpp += `inline constexpr double kSuppressionDartShare = ${num(parcaGecis.pens_eskalasyonu.supresyon_dagilimi.pensShare)};\n`;
hpp += `// FBA -> prenses bandı (curvysewingcollective, KAYNAK ZAYIF) — KAYIT.\n`;
hpp += `inline constexpr double kFbaPrincessMinMM = ${num(parcaGecis.pens_eskalasyonu.fbaPrenses.minMM)};\n`;
hpp += `inline constexpr double kFbaPrincessMaxMM = ${num(parcaGecis.pens_eskalasyonu.fbaPrenses.maxMM)};\n`;
hpp += `\n} // namespace contract\n} // namespace stitchu\n`;

// ---- JS (web + worker share the same content) --------------------------------
const pub = {
  version: tables.version,
  draft: {
    skirtLengthMM: tables.draft.skirtLengthMM,
    gatherRatios: Object.fromEntries(Object.entries(tables.draft.gatherRatios).filter(([k]) => !k.startsWith('_'))),
    euSizes: tables.draft.euSizes,
    euSizeChart: Object.fromEntries(tables.draft.euSizes.map((label) => [label, tables.draft.euSizeChart[label]])),
    euSizeChartFields: tables.draft.euSizeChart._fields,
  },
  flat: { unitPX: tables.flat.unitPX, len: tables.flat.len, size: tables.flat.size },
  mappings: {
    sleeveHeadToSleeveCap: Object.fromEntries(Object.entries(tables.mappings.sleeveHeadToSleeveCap).filter(([k]) => !k.startsWith('_'))),
    nullEquivalence: Object.fromEntries(Object.entries(tables.mappings.nullEquivalence).filter(([k]) => !k.startsWith('_'))),
    backDetailSplit: Object.fromEntries(Object.entries(tables.mappings.backDetailSplit).filter(([k]) => !k.startsWith('_'))),
    seenFlags: tables.mappings.seenFlags,
  },
};
let js = `// ${HEADER}\n// Single source for every shared cross-layer value + the vision-reading\n// schema (embedded from contract/garment-spec.schema.json $defs.visionReading\n// so the browser validates without fetching the contract dir).\n\nexport const CONTRACT = ${JSON.stringify(pub, null, 2)};\n\nexport const VISION_SCHEMA = ${JSON.stringify(schema.$defs.visionReading, null, 2)};\n\n// F2-vision: photo-reading carriage contract (embedded from\n// contract/vision-tasima-v1.json — ratio wires + out-of-vocab mapping).\nexport const VISION_TASIMA = ${JSON.stringify(visionTasima, null, 2)};\n\n// F7-edit: edit-locality contract (embedded from contract/edit-locality-v1.json)\n// — zones + untouchable panel patterns + field->zone map, so the create screen\n// runs the SAME locality judgement the gate (edit_locality_check.mjs) runs.\nexport const EDIT_LOCALITY = ${JSON.stringify({ zones: editLocality.zones, fieldZones: editLocality.fieldZones }, null, 2)};\n`;

// ---- C++ composition matrix (K2) ---------------------------------------------
// compose_check (ctest) re-derives every class by drafting and compares against
// these declared rules. The matrix declares behavior, it never changes it.
const esc = (s) => String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
let comp = `#pragma once\n// GENERATED by engine/tools/gen-contract.mjs from contract/composition.json — DO NOT EDIT.\n// K2 composition contract (2026-07-19): the declared component x host and\n// component x component conflict matrix. engine/tests/compose_check.cpp is the\n// ratchet: it drafts every combination and fails on any declared-vs-observed drift.\n\nnamespace stitchu {\nnamespace contract {\n\nstruct ComposeRule { const char* host; const char* feature; const char* cls; };\nstruct ComposePair { const char* a; const char* b; const char* cls; };\n\ninline constexpr ComposeRule kComposeHostRules[] = {\n`;
for (const r of composition.matrix.hostRules) {
  comp += `    {"${esc(r.host)}", "${esc(r.feature)}", "${esc(r.class)}"},\n`;
}
comp += `};\n\ninline constexpr ComposePair kComposePairRules[] = {\n`;
for (const r of composition.matrix.pairRules) {
  comp += `    {"${esc(r.a)}", "${esc(r.b)}", "${esc(r.class)}"},\n`;
}
comp += `};\n\n} // namespace contract\n} // namespace stitchu\n`;

// ---- write / check -----------------------------------------------------------
const outputs = [
  ['engine/src/contract.gen.hpp', hpp],
  ['engine/src/composition.gen.hpp', comp],
  ['web/js/contract.gen.js', js],
  ['backend/contract.gen.js', js],
];
const check = process.argv.includes('--check');
let drift = 0;
for (const [rel, content] of outputs) {
  const path = join(root, rel);
  if (check) {
    let cur = '';
    try { cur = readFileSync(path, 'utf8'); } catch { /* missing counts as drift */ }
    if (cur !== content) { console.error(`DRIFT: ${rel} out of sync with contract/tables.json (run gen-contract.mjs)`); drift = 1; }
  } else {
    writeFileSync(path, content);
  }
}
if (check) {
  if (drift) process.exit(1);
  console.log('contract.gen outputs in sync');
} else {
  console.log('wrote ' + outputs.map(([r]) => r).join(', '));
}
